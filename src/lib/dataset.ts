/** 将全部领域数据切片为 RAG 语料库（可复现、可引用） */
export function buildRagCorpus(): RagChunk[] {
  const chunks: RagChunk[] = [];
  const push = (source: string, sourceType: RagChunk['sourceType'], title: string, text: string) => {
    // 按句子切片，长文本进一步按 180 字窗口切分
    const sentences = text.split(/(?<=[。；！？\n])/).filter((s) => s.trim());
    let buf = '';
    sentences.forEach((s, i) => {
      if (buf.length + s.length > 180 && buf) {
        chunks.push({ id: `chunk-${chunks.length}`, source, sourceType, title, text: buf.trim() });
        buf = '';
      }
      buf += s;
      if (i === sentences.length - 1 && buf.trim()) {
        chunks.push({ id: `chunk-${chunks.length}`, source, sourceType, title, text: buf.trim() });
      }
    });
  };

  majors.forEach((m) => {
    push(`培养方案/${m.name}`, '培养方案', `${m.name} · 培养目标与课程体系`,
      `${m.name}（专业代码 ${m.code}，${m.college}，${m.category}，在校生 ${m.students} 人）。培养目标：${m.objectives.join('；')}。主要课程：${m.courses.join('、')}。`);
  });
  courses.forEach((c) => {
    push(`课程大纲/${c.name}`, '课程大纲', `${c.name} · 教学大纲`,
      `${c.name}：${c.credits} 学分 / ${c.hours} 学时，课程类别「${c.category}」。覆盖知识点：${c.knowledgePoints.join('、')}。`);
  });
  jobs.forEach((j) => {
    push(`招聘JD/${j.title}`, '招聘JD', `${j.title} · 岗位描述`,
      `${j.title}（${j.industry}·${j.region}，在招 ${j.count} 个，薪资 ${j.salary}，学历 ${j.education}）。${j.jd} 核心技能标签：${j.skills.join('、')}。`);
  });
  policyDocs.forEach((d) => push(`政策文件/${d.title}`, '政策文件', d.title, d.text));
  push('术语词典/跨域对齐', '术语词典', '教育—产业跨域语义对齐词典',
    knowledgePoints.filter((k) => k.aliases.length).map((k) => `「${k.name}」≈「${k.aliases.join(' / ')}」`).join('；') + '。');
  return chunks;
}

